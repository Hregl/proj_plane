//  依据：ENG-09 §5.1（类型定义冻结）、§2.1（变换方向）、§2.3（长度单位）
//
//  命名语义（ENG-09 §2.1，冻结）：变换量一律命名为 <A>To<B>，语义为
//  "把在 A 系中表达的坐标转换到 B 系"：
//
//      p_B = AToB * p_rotation
//
//  该方向约定是 SYS-13 §5 坐标链自洽的前提。ENG-09 §2.1 记录了一次实际
//  漂移：SYS-05 §11.2 把合成结果命名为 shipToAircraft，而链方向算出的
//  是 aircraft→ship，两者互为逆变换。**字段名写反不会有编译错误、
//  不会有运行期报错，只会让结果转置** —— 故本约定必须在头文件中可见。
//
//  ⚠ 与工作流文档的偏离（3.md §五、5.md §四 用的是 cv::Mat rotation
//     且默认构造为单位阵）：
//  1. ENG-09 §5.1 冻结 rotation 为 **cv::Matx33d**（固定尺寸）。
//     理由见 §2.7："矩阵字段使用固定尺寸类型（cv::Matx33d 而非 cv::Mat），
//     避免运行时尺寸错误"。cv::Mat 的默认构造是**空矩阵**，做乘法会抛
//     异常或静默产生空结果；而 Matx33d 的尺寸在编译期已知。
//  2. 默认值取**单位阵**而不是 3.md 的 cv::Mat::eye —— 语义一致，只是类型
//     固定化。默认构造必须代表"恒等变换"：若为零矩阵（cv::Matx33d{} 的
//     值），则任何未显式赋值的 Transform 都是奇异矩阵，"无变换"的含义
//     被静默破坏。
//     此处用成员初始化器实现（ENG-09 §2.7 的"POD 语义"理解为"纯数据、
//     无业务方法"，成员初始化器不改变字段名、字段顺序与内存布局）。
// ============================================================================

#include <opencv2/core.hpp>

namespace aircraft
{
namespace data
{

/// 刚体变换：p_B = rotation · p_A + translation
struct Transform
{
    /// 3x3 正交旋转矩阵，右手系。默认单位阵 = 无旋转。
    cv::Matx33d rotation = cv::Matx33d::eye();

    /// 平移向量，单位 **m**（ENG-09 §2.3；舰载场景量级 40~300 m）。
    /// 禁止混用毫米——OpenCV 标定工具链默认输出毫米，单位转换必须在
    /// CalibrationManager::load() 内一次性完成，不得泄漏到算法层。
    cv::Vec3d translation = cv::Vec3d(0.0, 0.0, 0.0);
};

}  // namespace data
}  // namespace aircraft
