#pragma once

// ============================================================================
//  src/data/DeviceIdentity.h
//
//  依据：ENG-09 V2.3 §5.30（设备身份契约，冻结）、§6.1（CameraConfig）
//        SYS-04 V2.4 §6.1 / SYS-06 V2.3 §6.1
//        裁决 C-01 v1.7（设备身份绑定）
//
//  作用：把"**这台设备是谁**"与"**它在系统里担任什么角色**"分开表达。
//  这是本批的一项实质修正 —— 见下。
//
//  ⚠ 四个概念此前被混为一谈（CameraConfig.h 的旧注释把 `cameraId`
//  说成"设备序列号"，而 `cameraId` 实际取值为 `cam25` 这样的**逻辑名**）：
//
//    | 概念 | 含义 | 来源 |
//    |---|---|---|
//    | `role` | 功能位 CAM25/50/100 | **配置/装配** |
//    | 逻辑 `cameraId` | 通道逻辑名（`cam25`） | **配置** `camera.yaml` 的 `id` |
//    | 设备型号 | 设备类型（`A7A20MU201`） | **SDK 枚举回报** |
//    | 设备序列号 | **本台**唯一标识 | **SDK 枚举回报** |
//
//  为什么这个区分是硬性的：**型号匹配不能替代设备身份匹配**。
//  现场有三台同型号相机，按"第 0 个设备"打开就会把 CAM25 的配置
//  下发给 CAM100 那台 —— 而两台设备**都不会报错**：
//  内参用错了焦段的标定，测量角会出现系统性偏差，且没有任何一处
//  能发现（因为型号是对的）。故打开设备一律按**序列号精确匹配**。
//
//  ⚠ 本结构体**不进** `ImageFrame`：它是装配期的事实，每帧重复携带
//  等于把同一个装配结论复制到每一帧上，还会催生"帧说序列号是 A、
//  装配摘要说是 B"的不一致窗口。装配摘要与日志读取它即可。
// ============================================================================

#include <optional>
#include <string>

namespace aircraft
{
namespace data
{

/// 一台设备（相机）的身份。
///
/// "未取得"有两种表达，**不得**混用：
///   · `queried == false` —— 根本没问过 SDK（虚拟后端即此类）；
///   · `queried == true` 而字段为空/`nullopt` —— 问过，但设备没回报。
/// 把后者写成前者，会让"真实后端取不到序列号"看起来像"这一路本来
/// 就没有身份概念"，从而在装配摘要里被静默放过。
struct DeviceIdentity
{
    /// 设备型号（`IMV_DeviceInfo::modelName`）。未取得 = 空串。
    /// ⚠ 本字段**只放型号**：不得为了"让界面好看"填入 `"virtual"`、
    /// `"unknown"` 之类的非型号内容 —— 后端类型由装配摘要的**独立一栏**
    /// 表达，混进来会让"型号列"失去机读意义。
    std::string modelName;

    /// 设备序列号（`IMV_DeviceInfo::serialNumber`）。未取得 = `nullopt`。
    ///
    /// ⚠ SDK 结构体**没有**"序列号是否有效"的标志位（§2.5 已核），
    /// 故"未取得"的判据只能是**字段为空串**（`serialNumber[0] == '\0'`）。
    std::optional<std::string> serialNumber;

    /// 是否真的向 SDK 查询过（虚拟后端 = false）。
    bool queried = false;
};

}  // namespace data
}  // namespace aircraft
