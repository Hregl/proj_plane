namespace aircraft
{
namespace data
{

/// 单个设备（相机 / 转台 / 触发）的生命周期状态。
enum class DeviceState
{
    UNKNOWN,  ///< 尚未探测（启动初值）
    INIT,     ///< 已创建，正在初始化（SDK 打开、参数下发）
    READY,    ///< 初始化完成、尚未开始取流/运动
    RUNNING,  ///< 正常工作
    ERROR,    ///< 故障。SYS-08 §7.2 规定硬件故障**不重试**，直接按 §7.5〔引用无效·依据待裁决·见 Q-D2〕 降级或 FAILED

    /// 设备不在（011-A1 新增，裁决 C-01 v1.7）。
    ///
    /// ⚠ **只**在 `OpStatus::Disconnected` 时置位，即：SDK 错误码的注释
    /// **明确**表示设备未连接（−118 `IMV_NOT_CONNECTED`「设备未连接」），
    /// 或**枚举结果里没有配置的目标序列号**（这是一个直接观察到的事实，
    /// 不是从错误码推断的）。`Timeout`／`NoFrame`／`NotStarted`／
    /// `CorruptFrame`／`SdkError` **都不置位** —— 它们是本轮取帧的瞬态或
    /// 未知结果，不是"设备不在了"。
    ///
    /// ⚠ 措辞纪律：本值与之对应的文本一律写"**按 SDK 错误码判定为断连，
    /// 未经连接事件确认**"。本批**不注册** `IMV_SubscribeConnectArg`
    /// （理由见 ENG-09 V2.3 §14 附录 B 第 1 条：回调在 SDK 自己的线程上执行，而
    /// backend 归设备线程独占、不保证线程安全；要接它必须先建一条
    /// 跨线程投递路径，那属于"完整恢复策略"），∴ **不得**写成
    /// "已确认断连"。
    ///
    /// ⚠ 本枚举**只表达状态，不裁定恢复策略**：此处**不写**"断连可重连、
    /// 故障不重试"之类的处置结论 —— 那属于待裁决的 Q-D1，且 SYS-08 的
    /// 相关条文本身存在撞号/悬空（见《SYS-08-§7引用勘误.md》）。
    DISCONNECTED
};

}  // namespace data
}  // namespace aircraft
