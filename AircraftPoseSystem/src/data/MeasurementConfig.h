//  ENG-09 §6.5 裁决段）：
//    - RetryManager（SYS-08 §7.6）是这些字段的**唯一读取者**；
//    - 各状态（含 AlignmentController、StateMachine）不得自持计数器，
//      也不得定义超时常量；
//    - 需要知道"还能试几次"时，向 RetryManager 查询 attempts()，
//      而不是在本地维护一份计数。
//
//  为什么这条约束是硬性的：重试次数分散在多处时，
//  "ALIGN 最多 8 次"这一事实会存在于多个代码位置，
//  任何一处改动都不会引起其他处报错，最终表现为
//  实测重试次数与 SYS-08 §7.3 的设计值不符 ——
//  而设计值直接决定 §7.2 的总时间预算（非 SEARCH 合计 37.8 s < T_task 60 s）。
//  预算被突破不会报错，只会让任务频繁撞上 kErrTaskTimeout(9001)。
//
//  ⚠ taskTimeoutNs 必须可注入（ENG-09 §6.5 明确要求）：
//  SYS-08 §10 的收敛性测试需要把 T_task 设为短值（如 2 s）来快速
//  遍历状态机的超时路径。因此该字段**不得**以编译期常量形式硬编码 ——
//  默认值 60e9 只是构造时的初值，必须能被 yaml 覆盖。
//
//  ⚠ 单位混用提示：本结构体同时包含 ns（超时）与 m / deg / pixel
//  （几何量）。每个字段的注释都标了单位，移植时不要靠字段名猜。
// ============================================================================

// ============================================================================
//  ⚠ 本文件引用的 SYS-08 §7.x 经核实为悬空／撞号引用（2026-09-26 复核），依据待裁决，见《待裁决问题汇总》Q-D2 与《SYS-08-§7引用勘误.md》；正文引用仅描述现行行为，不作为冻结依据。
