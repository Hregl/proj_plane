// ============================================================================
//  src/data/MultiCameraFrame.h
//
//  依据：ENG-09 §4.1、§5.6（类型定义冻结）、§2.5（时间戳）
//
//  ENG-09 §5.6 注明"三处文档定义一致，直接沿用" —— 本类型是少数没有裁决
//  的类型之一。
//
//  ⚠ 字段集合的唯一一次变更：**裁决 D-C02-6（2026-09-23 已批准）新增
//    `exposureIndex`**。ENG-09 §5.6 冻结的字段是 4 个，本字段是第 5 个 ——
//    这是一次**冻结结构体的扩展**，已走裁决而不是自行添加。理由是该判据
//    （"三路属于同一次曝光"）在真实硬触发下无处承载：原先只能用三路
//    `frameId` 相等来表达，而那在真机上恒不成立（详见字段说明）。
//
//  ⚠ triggerTimestamp 的取值规则（ENG-09 §2.5，冻结）：
//      取该组三帧中 timestampNs 的**最大值**
//  为什么取最大而不是平均或最小：同步校验关心的是"这一组帧能代表哪一时刻"。
//  取最小值会让整组的时间戳早于最晚一帧的实际曝光时刻，使后续以它为基准
//  计算的运动补偿（转台在动的场景）产生方向固定的系统偏差；取最大值保守，
//  且与"Synchronizer 必须集齐三帧才能输出"的语义一致 —— 组的时间戳就是
//  最后到齐那一帧的时间。
//
//  ⚠ 本结构体**不含 synchronized 标志位**（1.md Phase 2 的 3.md §七 曾定义
//     bool synchronized；D-C02-6 的结构体草稿里也再次出现过）。
//  结论**仍然是不加**，理由如下，请勿按草稿补上：
//    1. 它表达的判据已经有了归属：三帧时间戳极差是否在
//       `TriggerConfig::syncToleranceNs` 之内 —— 那是
//       `optical::CameraSynchronizer` 的职责（SYS-06 §8），
//       判据是**算出来的结论**，不是**存下来的字段**；
//    2. 同一个事实两处存储，必然出现二者不一致的状态（三帧时间戳明明超差、
//       而这个布尔量还是上次的 true）—— 与 C-04 删除 `bool moving`
//       是同一条理由；
//    3. 真要表达"不同步"，需要的是**它为什么不同步**（极差多少 ns、
//       哪一路缺帧），一个 bool 两者都答不了。
//  ⚠ 而当前真正的问题不是"缺这个字段"，是 `CameraSynchronizer`
//    **在运行路径上从未被构造**（`grep` 全 src 只有注释命中，
//    `SystemInitializer` 未装配、`MultiCameraManager::capture()` 只判
//    "≥2 路"）。即 SYS-06 §8 的同步判据当前**根本没在跑** ——
//    补一个 bool 字段只会让这件事看起来已经解决了。已登记 README §6，
//    属于 011-A0（真实硬触发）之前必须闭合的一项。
// ============================================================================

#include <cstdint>

#include "data/ImageFrame.h"

namespace aircraft
{
namespace data
{

/// 三相机同步采集结果。
struct MultiCameraFrame
{
    ImageFrame cam25;
    ImageFrame cam50;
    ImageFrame cam100;

    /// 主机 CLOCK_MONOTONIC 时间戳，单位 ns。
    /// 取三帧中 timestampNs 的**最大值**（ENG-09 §2.5）。
    uint64_t triggerTimestamp = 0;

    /// "同一次曝光"的序号 —— 本组三帧属于第几次触发曝光（裁决 D-C02-6）。
    ///
    /// ⚠ 语义是"**曝光序号**"，**不是** `ImageFrame::frameId`：
    /// `frameId` 是**每台相机自己的**帧计数器，三台上电时刻不同则计数起点
    /// 不同，真实硬件上 `cam25.frameId == cam50.frameId == cam100.frameId`
    /// **根本不成立**。若把它当作"同一次曝光"的判据，该判据在真机上永远
    /// 失败，而最省事的"修法"是把它放宽或删掉 —— 等于亲手拆掉安全网。
    ///
    /// ⚠ 本字段**必须**满足：同一组三帧共享同一个值，且该值随每次曝光
    /// 单调递增。它的唯一生产者是 `device::MultiCameraManager::capture()`
    /// （一轮 `capture()` 恰对应一次触发曝光），做法是**首帧偏移锁定**：
    /// 记下各路首次观察到的 `frameId` 作为基准，之后取
    /// `frameId − 基准`。该做法对虚拟相机（计数器从 0 起）与真实相机
    /// （计数器有任意起点）**同时成立**，故 011-A0 无需再实现一遍偏移锁定，
    /// 只需保证 `ImvCameraBackend` 报出的 `frameId` 单调。详见
    /// `MultiCameraManager.h` 的说明与 README §6。
    ///
    /// ⚠ 值为 0 表示**未定**（首帧尚未锁定基准，或本轮没有任何一路可用）。
    /// 调用方不得把 0 当作"第 0 次曝光"。
    uint64_t exposureIndex = 0;
};

}  // namespace data
}  // namespace aircraft
