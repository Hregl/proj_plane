#pragma once

// ============================================================================
//  src/data/PixelFormat.h
//
//  依据：ENG-09 V2.3 §5.28（像素格式与载荷契约，冻结）、§6.1（camera.yaml）
//        SYS-04 V2.4 §4.1（ImageFrame）
//        裁决 C-01 v1.7（A1 数据契约）
//
//  作用：像素格式的**项目自有定义**。SDK 的格式常量（`IMV_GVSP_PIX_*`）
//  只允许出现在适配层（`ImvCameraBackend.cpp`），由那里的映射表转成本文件的
//  枚举值。上层一律只看这里的类型 —— 这与 SystemConfig / ErrorInfo 的做法
//  一致：**设备常量不进公共类型**，否则换一家相机就要改上层。
//
//  ⚠ 为什么格式码要有"有效位 / 打包 / 对齐 / 字节序"四个维度，而不是一个
//  `Mono12` 就够：12 位数据的**存储形态**有三种彼此独立的不确定性 ——
//    ① 一个像素占几个字节（1.5 打包 / 2 字节容器）；
//    ② 12 个有效位落在容器的哪一端（低位对齐补零 / 高位对齐）；
//    ③ 多个字节的组装顺序（小端 / 大端）。
//  它们任一取错，显示图都会**看起来是一张图**（不会崩、不会报错），
//  只是每个像素的灰度值系统性偏移 —— 而灰度直接进入特征提取，
//  最终表现为测量角的偏差。一个 `Mono12` 枚举值说不出这三件事，
//  故必须分开表达，且**每一项都随帧落盘**（ENG-09 §6.5 结果包元数据）。
//
//  ⚠ 本批（011-A1）的支持范围（不是"留待将来"的含糊表述）：
//    · 实现：`Mono8` / `Mono12` / `BGR8`；
//    · `Mono12Packed`：返回 `NotImplemented`（本批无该格式需求，
//      属**范围**问题）。⚠ 其格式码 `0x010C0006` 在官方格式值表中归
//      **GigE Vision 2.0** 的 `Mono12Packed`，而 **PFNC 的 `Mono12p = 0x010C0047`
//      是另一项** —— 将来启用时必须按**该项实际所属规范**实现，
//      不得写成"按同一种 PFNC 打包规则实现即可"；
//    · 未知格式码：**明确失败**（`OpStatus::NotImplemented`），不回落、不猜测。
// ============================================================================

#include <cstdint>

namespace aircraft
{
namespace data
{

/// 像素格式（项目定义）。
///
/// 数值顺序与本工程无关（不落盘、不参与比较），故不指定底层类型。
enum class PixelFormat
{
    /// 8 位灰度。SDK 侧对应 `gvspPixelMono8 = 0x01080001`（＝PFNC 同码）。
    Mono8,

    /// 12 位灰度，**2 字节容器**（SDK 的 `OCCUPY16BIT`）。
    /// SDK 侧对应 `gvspPixelMono12 = 0x01100005` ＝ **PFNC 的 `Mono12`**。
    /// 有效位位置由 PFNC 2.4 §6.1.1 规定为**低位对齐、高位补零**。
    Mono12,

    /// 12 位灰度，1.5 字节/像素打包。SDK 侧对应 `gvspPixelMono12Packed
    /// = 0x010C0006`，归 **GigE Vision 2.0**（见文件头 ⚠）。
    /// 本批**不实现**。
    Mono12Packed,

    /// 3 通道 8 位 BGR。SDK 侧对应 `gvspPixelBGR8 = 0x02180015`。
    BGR8
};

/// 打包方式（一个像素在缓冲里占几个字节）。
enum class Packing
{
    /// 未打包：每像素按整数个字节存放（1 / 2 / 3 字节）。
    Unpacked,

    /// 12 位打包：两个像素共 3 字节。本批不实现。
    Packed12
};

/// 有效位对齐（12 位数据落在 16 位容器的哪一端）。
///
/// ⚠ 本批**只产出** `LsbZeroPadded`：`Mono12` 的依据是 PFNC 2.4 §6.1.1
/// 与图 6-3（低位对齐、未使用的高位补零），而 SDK 的格式码逐位等于 PFNC 码
/// （见 ImvCameraBackend.cpp 的映射表注释）。
/// **这不是"未知就失败"的运行期分支** —— 另两个取值在本批**不可达**，
/// 一旦出现即按契约错误拒绝（`OpStatus::ContractViolation`）。
/// 之所以仍保留枚举值：将来启用 `Mono12Packed` 或换相机时，
/// "上游给的帧声称自己是什么对齐"必须能被**表达出来并被拒绝**，
/// 而不是被静默当成低位对齐去解码。
enum class BitAlignment
{
    LsbZeroPadded,  ///< 低位对齐，高位补零（本批 `Mono12`）
    MsbAligned,     ///< 高位对齐（本批不实现，出现即拒绝）
    Unknown         ///< 未知（本批不实现，出现即拒绝）
};

/// 多字节样本的组装顺序。
///
/// ⚠ 这是**适配层的声明**，不是 SDK 的保证（依据与核实方式见 ENG-09 V2.3
/// §4.1 与 `RawImagePayload::declaredByteOrder` 的注释）。
enum class ByteOrder
{
    LittleEndian,
    BigEndian
};

/// 原始载荷的**必要性**策略。
///
/// 该字段与 `ImageFrame::captureFormat` 一起决定 Recorder 遇到
/// "`raw` 为空"时的行为（ENG-09 V2.3 §5.28 第 7 条的三分支表）——
/// 这是把"虚拟 8U 帧丢载荷无妨"与"真实 12 位帧丢载荷必须报错"
/// **在数据上分开**的判据，避免落盘时靠文件名、逻辑 `cameraId`
/// 或重查配置去猜。
enum class RawDataPolicy
{
    /// 原始载荷可选：显示图足以复现该帧（仅 8 位格式）。
    RawOptional,

    /// 原始载荷必需：显示图是**加工产物**，丢了就再也回不到原始数据
    /// （凡有效位深 > 8 的格式，本批即 `Mono12`）。
    RawRequired
};

}  // namespace data
}  // namespace aircraft
