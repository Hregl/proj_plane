#include "data/CaptureRound.h"
#include "data/ErrorInfo.h"
#include "data/MultiCameraFrame.h"

namespace aircraft
{
namespace device
{

/// 多相机管理器接口（SYS-06 §5.2）。
///
/// ⚠ 降级语义（SYS-08 §7.5〔引用无效·依据待裁决·见 Q-D2〕，实现必须遵守）：
///   | 可用相机数 | 行为 |
///   |    3      | 正常 |
///   |    2      | **降级继续**，禁用故障相机 |
///   |   ≤1      | 直接失败，ErrorInfo{code=1001} |
///
/// 因此 capture() 在只有 2 台可用时**必须返回 true**（而不是失败）——
/// 把"少一台"当作失败会白白丢弃 SYS-08 §7.5〔引用无效·依据待裁决·见 Q-D2〕 明确允许的降级能力，
/// 让一次本可完成的测量变成 FAILED。
class IMultiCameraManager
{
public:
    virtual ~IMultiCameraManager() = default;

    /// 初始化全部相机。返回 false 表示可用相机数不足（<2），
    /// 上层应直接 FAILED 并置 kErrCameraInsufficient(1001)。
    virtual bool initializeAll() = 0;

    /// 启动全部相机的采集。返回 false 的含义同 initializeAll()。
    virtual bool startAll() = 0;

    /// 停止全部相机。允许重复调用。
    virtual void stopAll() = 0;

    /// 同步采集一帧多相机图像。
    ///
    /// 成功时 frame.triggerTimestamp 取各相机 timestampNs 的**最大值**
    /// （ENG-09 §2.5 冻结）。取最大而非最小或均值的原因：
    /// 它保证 triggerTimestamp 不早于任何一路的实际曝光时刻，
    /// 使"该帧代表的时刻"这一语义不会超前于尚未采到的数据。
    ///
    /// 不可用的相机会在 frame 中留下默认构造的 ImageFrame
    /// （image 为空）。调用方应以 `frame.camXX.image.empty()` 判断该路是否
    /// 有效 —— 这比引入哨兵枚举可靠，见 CameraRole.h 的说明。
    ///
    /// ⚠ **期限由形参传入**（011-A1 改冻结签名）：
    /// `deadlineNs` ＝ 本次采集的**绝对**截止时刻，与 `setClock()` 提供的
    /// 时间读数**同一时基**。
    ///
    /// 为什么必须是形参而不是管理器自己算：管理器只知道自己什么时候被
    /// 调用，**说不出"这一次采集的期限是多少"** —— 那取决于调用方所处的
    /// 上下文（测量状态机当前状态的剩余预算、或空闲预览本次的期限）。
    /// 由管理器自行推算，等于让它去猜调用方的策略。
    /// ⚠ 管理器**不得缓存**上一轮收到的期限：缓存会把"上一次的截止时刻"
    /// 用到这一轮，而两轮之间的期限通常不同（本轮更晚），
    /// 表现为"明明还有预算却整轮不取帧"。
    ///
    /// @param deadlineNs 绝对截止时刻（ns，注入钟的时基）。剩余不足 1 ms
    ///        时实现**既不发软件触发令也不取帧**，各路记 `Timeout` +
    ///        `skippedReason = 预算耗尽`。
    /// @return 可用相机数 <2 时返回 false（上层应置 1001 并 FAILED）。
    virtual bool capture(data::MultiCameraFrame& frame,
                         uint64_t                deadlineNs) = 0;

    /// 最近一轮 `capture()` 的**每路结果与聚合**（011-A1 新增，**纯虚**）。
    ///
    /// ⚠ 为什么是**纯虚**而不是给一个 `{ return {}; }` 的默认实现：
    /// 默认空实现会让"**漏迁移**"静默通过 —— 某个实现忘了覆盖它，
    /// 上层拿到的是"三路全未尝试、0 帧"的空结果，而**没有任何错误**。
    /// 纯虚把遗漏变成**编译错误**。本仓恰有两个实现需要迁移
    /// （`MultiCameraManager` 与测试替身 `VirtualCameras`），
    /// 编译器会精确点名它们。
    ///
    /// 读者：`MeasurementController::updateDegradation()` 由"图非空"的
    /// 推断改为读本轮事实（降级/终止**决策一字不改**，只让**原因**如实）。
    virtual data::CaptureRound lastCaptureRound() const = 0;

    /// 上一次操作失败的原因（裁决 C-006）。
    ///
    /// ⚠ 为什么必须由接口提供而不是由上层猜：`capture()` 只回一个 bool，
    /// 而它失败的原因至少有两类**处置完全不同**的情形 ——
    /// "可用相机数不足"（1001，硬件故障，不重试）与
    /// "三路时间戳超差"（3002，瞬态，重采即可）。
    /// 上层若只凭 false 就自己编一个码，等于把这两类混为一谈。
    ///
    /// 实现者**应当**填写本字段；这里给出默认实现是为了不破坏既有实现
    /// （本接口不是冻结 ICD，但也没必要为此让所有实现者改代码）。
    /// 未填写（code == 0）时上层按兜底码 9004 记录，而**不会**冒充某个
    /// 具体码 —— 宁可少报一个具体码，也不要凭空造一个不成立的根因。
    virtual data::ErrorInfo lastError() const { return data::ErrorInfo{}; }
};

}  // namespace device
}  // namespace aircraft
