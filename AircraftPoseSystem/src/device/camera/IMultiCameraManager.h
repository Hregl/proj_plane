// ============================================================================
//  src/device/camera/IMultiCameraManager.h
//
//  依据：SYS-06 §5.1 / §5.2（接口冻结）、ENG-09 §4.3、ENG-01 §6
//
//  作用：三相机同步采集的管理者。它把三个 backend 的并发采集
//  收敛为**一个** MultiCameraFrame，使上层（application / algorithm）
//  永远只面对"三个视角属于同一时刻"这一个前提，而不必各自处理
//  三路异步到达的图像。
//
//  ⚠ 签名依据（2026-09-26 改写，裁决 C-01 v1.7）：
//  本行原文写"接口签名**逐字**遵循 SYS-06 §5.2（4 个纯虚函数），未增删"。
//  该说法自本批起**不再成立**：本批为 `capture()` 增加了 `deadlineNs`
//  形参（期限必须由调用方传入，见其注释），并新增了纯虚的
//  `lastCaptureRound()`。故改为：**签名按 SYS-04 V2.4 §6.1 与
//  SYS-06 V2.3 §5.1 冻结；相对 V2.2 的增删见 C-01 v1.7。**
//  文件位置与命名空间的偏离同 ICameraBackend.h。
//
//  ⚠ 本接口**不承载降级信息**，这是有意的：
//  SYS-08 §7.5〔引用无效·依据待裁决·见 Q-D2〕 要求结果包记录 `degraded=true` 与 `cameras_available`，
//  而这两个事实属于**管理器状态**，不属于某一帧。
//  若把它们塞进 MultiCameraFrame，则每帧都要重复携带同一个管理器级事实，
//  且存在"帧说降级了、管理器说没降级"的不一致窗口。
//  故：帧只含数据，状态由具象类 MultiCameraManager 的查询方法提供
//  （接口本身保持冻结，不因此增补方法）。
// ============================================================================

// ============================================================================
//  ⚠ 本文件引用的 SYS-08 §7.x 经核实为悬空／撞号引用（2026-09-26 复核），依据待裁决，见《待裁决问题汇总》Q-D2 与《SYS-08-§7引用勘误.md》；正文引用仅描述现行行为，不作为冻结依据。
