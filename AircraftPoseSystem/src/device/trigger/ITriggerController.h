namespace aircraft
{
namespace device
{

/// 相机触发控制接口（SYS-06 §9.1）。
class ITriggerController
{
public:
    virtual ~ITriggerController() = default;

    /// 初始化触发源。失败时上层按 SYS-08 §7.5 降级为软触发。
    virtual bool initialize() = 0;

    /// 使能触发输出。失败 → 降级为软触发并置 code=3001。
    virtual bool enable() = 0;

    /// 产生一次触发。
    ///
    /// 语义：使三台相机**同时**开始曝光。
    /// 硬触发下由硬件同时发出三路脉冲，同步精度由硬件保证；
    /// 软触发下由软件顺序调用各相机的触发接口，
    /// 同步精度取决于调用开销（毫秒量级），
    /// 与硬触发的微秒级相差三个数量级 —— 这正是降级有代价的原因。
    ///
    /// @return false 表示本次触发未生效，上层应按 §7.5 处理。
    virtual bool trigger() = 0;

    /// 关闭触发输出。必须可重复调用。
    virtual void disable() = 0;
};

}  // namespace device
}  // namespace aircraft
