//  依据：SYS-06 §9.1（接口冻结）、§8（三相机同步采集）
//        SYS-08 §7.5（触发故障降级）
//        ENG-09 §4.3、ENG-01 §6
//
//  作用：相机触发源抽象。硬触发使三台相机在同一时刻曝光，
//  这是 MultiCameraFrame "三路属于同一时刻"这一前提的**唯一**硬保障。
//
//  ⚠ 触发失效的处理是**降级而非失败**（SYS-08 §7.5〔引用无效·依据待裁决·见 Q-D2〕 冻结）：
//  "触发故障 → 降级为软触发（各相机自由运行 + 主机时间戳对齐）并记录；
//    软触发亦不可用则 FAILED"。
//  因此本接口的 enable() 返回 false 时，上层的正确动作是
//  置 kErrTriggerDegraded(3001) 并**继续测量**，而不是 FAILED。
//  代价是同步精度下降（自由运行的相机之间没有共同的曝光时刻），
//  故降级必须在 UI 上可见（§7.5〔引用无效·依据待裁决·见 Q-D2〕："不得静默降级"）——
//  降级后的精度可能已不满足 SYS-15 的误差预算。
//
//  ⚠ 本接口**不负责**同步验证。SYS-06 §8 把"时间戳检查、丢帧检测、
//  同步验证"列为软件职责，但该职责在 optical 层的 CameraSynchronizer
//  （ENG-01 §8），判据为 TriggerConfig::syncToleranceNs。
//  这样切分使触发控制器只面对硬件（发脉冲 / 收应答），
//  无需理解"多大的时间戳偏差算不同步"这一随场景变化的策略。
//
//  ⚠ 归属偏离（4.md 的 `src/interfaces/`）与命名空间偏离
//  （4.md 的 `aircraft::interfaces`）：同 ICameraBackend.h。
//  接口签名逐字遵循 SYS-06 §9.1。
// ============================================================================

