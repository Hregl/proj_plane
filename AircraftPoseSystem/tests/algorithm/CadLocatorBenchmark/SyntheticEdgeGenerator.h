#include <cstdint>
#include <vector>

#include <opencv2/core.hpp>

namespace cadbench
{

/// 一个结构点（"十字"角点）的解析真值与其棱线方向。
///
/// `x` / `y` 是**解析边界**所在的亚像素坐标（设计说明 §1.4 冻结的口径），
/// 不是"第一个亮像素的中心"。两者相差 0.5 pixel 量级 —— 该差值必须写进
/// report.json 的 `truth_convention`，否则本基准的数字与 README §6 第 57 行
/// 那组数字会被直接相减（它们差一个口径）。
struct CornerSpec
{
    double x = 0.0;
    double y = 0.0;
};

/// 生成参数。默认值即设计说明 §1.5 用例矩阵的"基准格"（Case A / θ=0° / 无退化）。
struct GenOptions
{
    int width = 640;
    int height = 480;

    /// 超采样倍数。**必须 ≥ 8**（设计说明 §1.1）。
    /// 取 1 时生成器会拒绝工作（见 .cpp 的 assertSupersampling）。
    int supersample = 8;

    /// 棱线相对像素栅格的夹角，单位度（设计说明 §1.5 维度 D）。
    /// θ=0° 表示棱线**与像素栅格对齐** —— 这是量化误差最纯粹的呈现。
    double thetaDeg = 0.0;

    /// 零均值高斯噪声的标准差，单位**灰度级**（设计说明 §1.5，评审裁定取 {0,5,10}）。
    double noiseSigma = 0.0;

    /// 高斯模糊的标准差，单位 pixel（0 表示不模糊）。
    double blurSigma = 0.0;

    /// JPEG 质量因子；100 表示**不压缩**（跳过有损往返）。
    int jpegQuality = 100;

    /// 随机种子（设计说明 §1.8）。噪声与压缩都由此决定，故可重放。
    uint64_t seed = 20260923;
};

/// 一次生成的结果。
struct GeneratedImage
{
    /// CV_8UC1 灰度图，尺寸 = (width, height)。
    cv::Mat image;

    /// 与生成所用**完全一致**的解析真值（设计说明 §1.4）。
    /// 不是"从图上反推"的 —— 是生成时用的那一份，这是可解析反解的含义。
    std::vector<CornerSpec> corners;

    /// 实际使用的超采样倍数（回抄，供 report.json 记录）。
    int supersample = 0;

    /// 本次生成实际施加的退化（回抄，供 report.json 记录）。
    GenOptions options;
};

/// 生成一幅"2×2 棋盘格角点"合成图。
///
/// 每个 `CornerSpec` 在该位置放一个由**两条非平行强度阶跃**（其夹角为
/// `thetaDeg`）分出的 2×2 象限图案：对角象限同亮度，相邻象限反相。
///
/// ⚠ 为什么不是"暗背景上的亮十字线"（设计说明 §1.2，沿用现有夹具的结论）：
///   一条亮线有**两条**强度阶跃、两条边缘链，而定位器的分组依据是
///   **梯度方向**（倍角聚类），两链倍角后同族 → 必然被并成一组 →
///   组内混有相距一个线宽的两条平行边缘 → 残差中位数下限 ~1.5 pixel →
///    **永远**无法满足冻结的 0.3 pixel 判据。失败与实现无关，是夹具自相矛盾。
///   真实的棱线是两个区域的交界（机翼对天空），只有一条阶跃。
///
/// 生成过程（设计说明 §1.1）：
///   1. 在 `ss × ss` 的细网格上逐点判定象限，得到 0/255 的**解析**图案；
///   2. `cv::INTER_AREA` 降采样（盒式平均）；
///   3. 按 `blurSigma` 模糊、按 `jpegQuality` 压缩、按 `noiseSigma` 加噪。
///
/// ⚠ **`ss` 必须按被测目标选，不是"≥ 8 就都行"** —— 本节写就时实测纠正过：
///   细网格是**硬判**亮/暗，盒式平均把灰度量化到 `n/ss`，
///   即**渲染量化 = 1/ss pixel**（ss=8 实测灰度只取 255 的 1/8 步长）。
///
///   | 被测目标 | 需要的 ss | 理由 |
///   |---|---|---|
///   | Baseline（误差 ~1 px） | 8 足够 | 实测 ss=8/16/32/64 给出**逐位相同**的读数 |
///   | 亚像素方法（目标 0.1~0.2 px） | **≥ 64** | 0.125 px 的渲染量化与被测量同量级，否则基准量的是夹具 |
///
///   本函数**不自动选** ss：自动选会让"测的是什么"变得不可见，
///   而本基准的全部价值就在于口径可见。
///
/// ⚠ 顺序：退化必须在降采样**之后**施加。在超采样图上加噪再盒式平均等于
///   自动降噪（ss² 倍），会把噪声强度糊掉 —— 那测的不是真实 CMOS 链路。
GeneratedImage generateCheckerCornerImage(
    const std::vector<CornerSpec>& corners,
    const GenOptions& options);

/// 设计说明 §2.5 V-3 的"表达能力对照"所需的**唯一**入口。
///
/// 在 `ss = 1` 下，一条竖直硬边判定为 `x >= W/2 + t`：**对整数 `x` 取值**，
/// 只要 `W/2 + t` 落在同一个整数格 `(k, k+1]` 内，任意两个 `t` 都给出
/// 完全相同的二值图像。于是"真值 200.37"这张图**根本不存在** ——
/// 拿它去比对，得到的偏差与 `t` 无关，基准会稳定地输出一个
/// **看起来正常却毫无意义**的数。
///
/// ⚠ **V-3 的正确形式：比较落在同一整数格内的两个偏移。**
///   实测：`t=0.1` vs `t=0.5` → 逐位相同 ✅；`t=0.9` vs `t=1.1` → 不同 ✅
///   （后者同时证明量化步长恰好是 1 pixel）。
///   **不要**用 `t=0.0` 与 `t=0.5` 比：`t=0.0` 使 boundary 恰好等于整数，
///   而判定式是 `>=`，该列算作亮，与 `t ∈ (0,1]` 的全部取值相反 ——
///   那是端点效应，按它写"任意两个 t 应相同"会**误判超采样未生效**。
cv::Mat generateDegenerateSs1Image(int width, int height, double subPixelOffset);

}  // namespace cadbench
